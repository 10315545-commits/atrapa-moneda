-- =========================================================
-- CREAR JUGADOR
-- =========================================================

create or replace function public.create_player(
    p_display_name text
)
returns public.players
language plpgsql
security definer
set search_path = public
as $$
declare
    v_number integer;
    v_player public.players;
begin

    if auth.uid() is null then
        raise exception 'No autenticado';
    end if;

    select *
    into v_player
    from public.players
    where id = auth.uid();

    if found then
        return v_player;
    end if;

    loop
        v_number :=
            floor(random() * 900000)::integer + 100000;

        exit when not exists (
            select 1
            from public.players
            where player_number = v_number
        );
    end loop;

    insert into public.players (
        id,
        player_number,
        display_name
    )
    values (
        auth.uid(),
        v_number,
        coalesce(
            nullif(trim(p_display_name), ''),
            'Jugador' || v_number
        )
    )
    returning *
    into v_player;

    insert into public.player_items (
        player_id,
        item_id,
        item_type
    )
    values
        (auth.uid(),'avatar1','avatar'),
        (auth.uid(),'basket1','basket'),
        (auth.uid(),'coin1','coin');

    return v_player;
end;
$$;

grant execute
on function public.create_player(text)
to authenticated;

