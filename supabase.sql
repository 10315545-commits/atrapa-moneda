-- =========================================================
-- CREAR TRADE
-- =========================================================

create or replace function public.create_trade(
    p_receiver_id uuid
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
    v_trade_id uuid;
begin

    if auth.uid() is null then
        raise exception 'No autenticado';
    end if;

    if p_receiver_id = auth.uid() then
        raise exception 'No puedes tradear contigo mismo';
    end if;

    if not exists (
        select 1
        from public.players
        where id = p_receiver_id
    ) then
        raise exception 'Jugador no encontrado';
    end if;

    insert into public.trades (
        sender_id,
        receiver_id
    )
    values (
        auth.uid(),
        p_receiver_id
    )
    returning id
    into v_trade_id;

    return v_trade_id;
end;
$$;

grant execute
on function public.create_trade(uuid)
to authenticated;

-- =========================================================
-- CAMBIAR OFERTA DE MONEDAS
-- =========================================================

create or replace function public.set_trade_coins(
    p_trade_id uuid,
    p_amount bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_trade public.trades;
begin

    if p_amount < 0 then
        raise exception 'Cantidad inválida';
    end if;

    select *
    into v_trade
    from public.trades
    where id = p_trade_id
      and status = 'pending'
      and (
        sender_id = auth.uid()
        or receiver_id = auth.uid()
      )
    for update;

    if not found then
        raise exception 'Trade no encontrado';
    end if;

    if v_trade.sender_id = auth.uid() then

        update public.trades
        set
            sender_coins = p_amount,
            sender_confirmed = false,
            receiver_confirmed = false,
            updated_at = now()
        where id = p_trade_id;

    else

        update public.trades
        set
            receiver_coins = p_amount,
            sender_confirmed = false,
            receiver_confirmed = false,
            updated_at = now()
        where id = p_trade_id;

    end if;
end;
$$;

grant execute
on function public.set_trade_coins(uuid,bigint)
to authenticated;

-- =========================================================
-- CONFIRMAR TRADE
-- =========================================================

create or replace function public.confirm_trade(
    p_trade_id uuid
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
    v_trade public.trades;
    v_sender_balance bigint;
    v_receiver_balance bigint;
begin

    select *
    into v_trade
    from public.trades
    where id = p_trade_id
      and status = 'pending'
      and (
        sender_id = auth.uid()
        or receiver_id = auth.uid()
      )
    for update;

    if not found then
        raise exception 'Trade no encontrado';
    end if;

    if v_trade.sender_id = auth.uid() then

        update public.trades
        set
            sender_confirmed = true,
            updated_at = now()
        where id = p_trade_id;

    else

        update public.trades
        set
            receiver_confirmed = true,
            updated_at = now()
        where id = p_trade_id;

    end if;

    select *
    into v_trade
    from public.trades
    where id = p_trade_id
    for update;

    if not (
        v_trade.sender_confirmed
        and
        v_trade.receiver_confirmed
    ) then

        return 'waiting';

    end if;

    select coins
    into v_sender_balance
    from public.players
    where id = v_trade.sender_id
    for update;

    select coins
    into v_receiver_balance
    from public.players
    where id = v_trade.receiver_id
    for update;

    if v_sender_balance < v_trade.sender_coins then

        update public.trades
        set
            status='cancelled',
            updated_at=now()
        where id=p_trade_id;

        raise exception 'El emisor no tiene suficientes monedas';

    end if;

    if v_receiver_balance < v_trade.receiver_coins then

        update public.trades
        set
            status='cancelled',
            updated_at=now()
        where id=p_trade_id;

        raise exception 'El receptor no tiene suficientes monedas';

    end if;

    update public.players
    set
        coins=coins-v_trade.sender_coins,
        updated_at=now()
    where id=v_trade.sender_id;

    update public.players
    set
        coins=coins-v_trade.receiver_coins,
        updated_at=now()
    where id=v_trade.receiver_id;

    update public.players
    set
        coins=coins+v_trade.receiver_coins,
        updated_at=now()
    where id=v_trade.sender_id;

    update public.players
    set
        coins=coins+v_trade.sender_coins,
        updated_at=now()
    where id=v_trade.receiver_id;

    update public.trades
    set
        status='completed',
        updated_at=now()
    where id=p_trade_id;

    return 'completed';
end;
$$;

grant execute
on function public.confirm_trade(uuid)
to authenticated;

-- =========================================================
-- CANCELAR TRADE
-- =========================================================

create or replace function public.cancel_trade(
    p_trade_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin

    update public.trades
    set
        status='cancelled',
        updated_at=now()
    where id=p_trade_id
      and status='pending'
      and (
        sender_id=auth.uid()
        or receiver_id=auth.uid()
      );

end;
$$;

grant execute
on function public.cancel_trade(uuid)
to authenticated;

