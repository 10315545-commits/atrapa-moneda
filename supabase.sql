-- =========================================================
-- JUGADORES
-- =========================================================

create table if not exists public.players (
    id uuid primary key references auth.users(id) on delete cascade,
    player_number integer unique not null,
    display_name text not null,
    coins bigint not null default 1000,
    role text not null default 'player'
        check (role in ('player','tester','admin','owner')),
    avatar text not null default 'avatar1',
    basket_skin text not null default 'basket1',
    coin_skin text not null default 'coin1',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- =========================================================
-- INVENTARIO
-- =========================================================

create table if not exists public.player_items (
    player_id uuid not null references public.players(id) on delete cascade,
    item_id text not null,
    item_type text not null
        check (item_type in ('avatar','basket','coin')),
    unlocked_at timestamptz not null default now(),
    primary key (player_id,item_id)
);

-- =========================================================
-- CHAT
-- =========================================================

create table if not exists public.chat_messages (
    id bigint generated by default as identity primary key,
    player_id uuid not null references public.players(id) on delete cascade,
    display_name text not null,
    message text not null
        check (char_length(message) between 1 and 200),
    created_at timestamptz not null default now()
);

-- =========================================================
-- TRADEOS
-- =========================================================

create table if not exists public.trades (
    id uuid primary key default gen_random_uuid(),

    sender_id uuid not null
        references public.players(id)
        on delete cascade,

    receiver_id uuid not null
        references public.players(id)
        on delete cascade,

    sender_coins bigint not null default 0
        check (sender_coins >= 0),

    receiver_coins bigint not null default 0
        check (receiver_coins >= 0),

    sender_confirmed boolean not null default false,
    receiver_confirmed boolean not null default false,

    status text not null default 'pending'
        check (
            status in (
                'pending',
                'completed',
                'cancelled',
                'expired'
            )
        ),

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- =========================================================
-- OBJETOS DEL TRADE
-- =========================================================

create table if not exists public.trade_items (
    trade_id uuid not null
        references public.trades(id)
        on delete cascade,

    player_id uuid not null
        references public.players(id)
        on delete cascade,

    item_id text not null,

    item_type text not null
        check (item_type in ('avatar','basket','coin')),

    primary key (trade_id,player_id,item_id)
);

-- =========================================================
-- EVENTOS GLOBALES
-- =========================================================

create table if not exists public.global_events (
    id bigint generated by default as identity primary key,
    actor_id uuid references public.players(id) on delete set null,
    actor_name text,
    type text not null,
    target_number integer,
    amount bigint,
    item_id text,
    message text,
    created_at timestamptz not null default now()
);

