-- =========================================================

create or replace function public.owner_give_coins(
    p_target_id uuid,
    p_amount bigint
)
returns public.players
language plpgsql
security definer
set search_path = public
as $$
declare
    v_role text;
    v_player public.players;
begin

    select role
    into v_role
    from public.players
    where id = auth.uid();

    if v_role not in ('owner','admin') then
        raise exception 'Sin permisos';
    end if;

    if p_amount <= 0 then
        raise exception 'Cantidad inválida';
    end if;

    update public.players
    set
        coins = coins + p_amount,
        updated_at = now()
    where id = p_target_id
    returning *
    into v_player;

    if not found then
        raise exception 'Jugador no encontrado';
    end if;

    return v_player;
end;
$$;

grant execute
on function public.owner_give_coins(uuid,bigint)
to authenticated;

